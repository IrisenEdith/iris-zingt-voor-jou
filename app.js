function setTheme(theme) {
  document.documentElement.dataset.theme = theme;
  localStorage.setItem("iris-theme", theme);
}

function getRoute() {
  return location.hash.replace("#", "") || "/";
}

function render() {
  const route = getRoute();
  const lyricMatch = route.match(/^\/lyrics\/(.+)$/);
  if (lyricMatch) {
    const song = songs.find((item) => item.id === lyricMatch[1]) || songs[0];
    main.innerHTML = renderLyrics(song);
  } else {
    const view = routes[route] || renderHome;
    main.innerHTML = view();
  }
  document.querySelectorAll(".nav-links a").forEach((link) => {
    const linkRoute = link.getAttribute("href").replace("#", "");
    link.classList.toggle("is-active", linkRoute === route || (route === "/" && linkRoute === "/"));
  });
  closeMenu();
  attachPageEvents();
  revealOnScroll();
  main.focus({ preventScroll: true });
  window.scrollTo({ top: 0, behavior: "auto" });
}

